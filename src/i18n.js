function getRememberedValue(node, language, originalValues, lastValues) {
  const currentValue = node.nodeValue;
  const remembered = originalValues.get(node);
  const lastValue = lastValues.get(node);

  if (remembered && (currentValue === lastValue || currentValue === translateValue(remembered.value, language))) {
    return remembered;
  }

  const trimmedValue = currentValue.trim();
  const reverseValue = localeReverseMaps[language]?.get(trimmedValue);
  const leading = currentValue.match(/^\s*/)?.[0] || "";
  const trailing = currentValue.match(/\s*$/)?.[0] || "";
  const value = reverseValue || trimmedValue;
  const next = { value, leading, trailing };
  originalValues.set(node, next);
  return next;
}

function translateTextNode(node, language, originalValues, lastValues) {
  const parent = node.parentElement;
  if (!parent || /^(INPUT|TEXTAREA|SCRIPT|STYLE|NOSCRIPT)$/.test(parent.tagName) || parent.isContentEditable) {
    return;
  }

  const remembered = getRememberedValue(node, language, originalValues, lastValues);
  const translated = `${remembered.leading}${translateValue(remembered.value, language)}${remembered.trailing}`;
  if (node.nodeValue !== translated) {
    node.nodeValue = translated;
  }
  lastValues.set(node, translated);
}

function translateAttributes(element, language, originalValues, lastValues) {
  for (const name of ["aria-label", "aria-description", "placeholder", "title"]) {
    if (!element.hasAttribute(name)) {
      continue;
    }

    let values = originalValues.get(element);
    if (!values) {
      values = new Map();
      originalValues.set(element, values);
    }
    let lastAttributes = lastValues.get(element);
    if (!lastAttributes) {
      lastAttributes = new Map();
      lastValues.set(element, lastAttributes);
    }

    const currentValue = element.getAttribute(name);
    let original = values.get(name);
    if (!original || (currentValue !== lastAttributes.get(name) && currentValue !== translateValue(original, language))) {
      original = localeReverseMaps[language]?.get(currentValue) || currentValue;
      values.set(name, original);
    }
    const translated = translateValue(original, language);
    if (currentValue !== translated) {
      element.setAttribute(name, translated);
    }
    lastAttributes.set(name, translated);
  }
}

function translateElementTree(root, language, textOriginals, textLastValues, attributeOriginals, attributeLastValues) {
  if (root.nodeType === Node.TEXT_NODE) {
    translateTextNode(root, language, textOriginals, textLastValues);
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_FRAGMENT_NODE) {
    return;
  }
  if (root.nodeType === Node.ELEMENT_NODE) {
    translateAttributes(root, language, attributeOriginals, attributeLastValues);
  }
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.nodeType === Node.TEXT_NODE) {
      translateTextNode(node, language, textOriginals, textLastValues);
    } else {
      translateAttributes(node, language, attributeOriginals, attributeLastValues);
    }
  }
}

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    const savedLanguage = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return LANGUAGES.some(({ code }) => code === savedLanguage) ? savedLanguage : "en";
  });
  const textOriginals = useRef(new WeakMap());
  const textLastValues = useRef(new WeakMap());
  const attributeOriginals = useRef(new WeakMap());
  const attributeLastValues = useRef(new WeakMap());
  const initialTitle = useRef(document.title);

  const setLanguage = useCallback((nextLanguage) => {
    if (!LANGUAGES.some(({ code }) => code === nextLanguage)) {
      throw new Error(`Unsupported language: ${nextLanguage}`);
    }
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
    setLanguageState(nextLanguage);
  }, []);

  useEffect(() => {
    const translate = (root) => translateElementTree(
      root,
      language,
      textOriginals.current,
      textLastValues.current,
      attributeOriginals.current,
      attributeLastValues.current,
    );

    document.documentElement.lang = language === "pa" ? "pa-IN" : language === "hi" ? "hi-IN" : "en";
    document.title = translateValue(initialTitle.current, language);
    translate(document.body);

    const observer = new MutationObserver((records) => {
      for (const record of records) {
        if (record.type === "characterData") {
          translate(record.target);
        } else if (record.type === "attributes") {
          translate(record.target);
        } else {
          record.addedNodes.forEach(translate);
        }
      }
    });
    observer.observe(document.body, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ["aria-label", "aria-description", "placeholder", "title"],
    });

    return () => observer.disconnect();
  }, [language]);

  const contextValue = useMemo(() => ({ language, setLanguage }), [language, setLanguage]);
  return createElement(LanguageContext.Provider, { value: contextValue }, children);
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within a LanguageProvider.");
  }
  return context;
}
