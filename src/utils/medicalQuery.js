const normalizeQueryText = (value) =>
  String(value)
    .toLowerCase()
    .replace(/[^\p{L}\p{M}\p{N}\s:-]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();

const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const medicalSynonyms = new Map();

for (const [term, aliases] of MEDICAL_QUERY_SYNONYMS) {
  for (const alias of [term, ...aliases]) {
    const normalizedAlias = normalizeQueryText(alias);

    if (normalizedAlias && !medicalSynonyms.has(normalizedAlias)) {
      medicalSynonyms.set(normalizedAlias, term);
    }
  }
}

const MEDICAL_SYNONYM_PATTERN = new RegExp(
  `(^|[\\s:-])(${[...medicalSynonyms.keys()]
    .sort((left, right) => right.length - left.length)
    .map((alias) => escapeRegExp(alias).replace(/\s+/g, "\\s+"))
    .join("|")})(?=$|[\\s:-])`,
  "gu",
);

const MEDICAL_SYNONYM_TERMS = new Set(
  [...medicalSynonyms.values()].filter(
    (term) => !QUERY_INTENT_TERMS.has(term),
  ),
);

export function normalizeMedicalQuery(value = "") {
  return normalizeQueryText(value)
    .replace(
      MEDICAL_SYNONYM_PATTERN,
      (match, boundary, alias) =>
        `${boundary}${medicalSynonyms.get(alias)}`,
    )
    .replace(/[^\p{L}\p{M}\p{N}\s:-]/gu, " ")
    .replace(/[^a-z0-9\s:-]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function isMedicalQuery(value = "") {
  const normalizedQuery = normalizeMedicalQuery(value);

  if (!normalizedQuery) {
    return false;
  }

  const queryWords = normalizedQuery.split(" ");
  const containsMedicalTerm = MEDICAL_TERMS.some((term) => {
    if (term.includes(" ")) {
      return (
        normalizedQuery === term ||
        normalizedQuery.includes(` ${term} `) ||
        normalizedQuery.startsWith(`${term} `) ||
        normalizedQuery.endsWith(` ${term}`)
      );
    }

    return queryWords.includes(term);
  });
  const containsMedicalSynonym = [...MEDICAL_SYNONYM_TERMS].some((term) => {
    if (term.includes(" ")) {
      return (
        normalizedQuery === term ||
        normalizedQuery.includes(` ${term} `) ||
        normalizedQuery.startsWith(`${term} `) ||
        normalizedQuery.endsWith(` ${term}`)
      );
    }

    return queryWords.includes(term);
  });

  return (
    containsMedicalTerm ||
    containsMedicalSynonym ||
    queryWords.some((word) => MEDICAL_ABBREVIATIONS.has(word)) ||
    MEDICAL_SUFFIX_PATTERN.test(normalizedQuery)
  );
}
